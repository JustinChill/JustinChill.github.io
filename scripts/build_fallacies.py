#!/usr/bin/env python3
"""Rebuild the fallacy cards in fallacies.html from data/Rhetological_Fallacies.csv.

Run from the repo root:

    python3 scripts/build_fallacies.py          # rewrite the generated block in place
    python3 scripts/build_fallacies.py --check  # exit 1 if the page is out of date

The CSV (columns: fallacy, definition, example, category) is the source of
truth. Everything between the `fallacies:start` and `fallacies:end` comments in
fallacies.html is generated: the family filter chips (with counts) and one
section of cards per family. Cards are sorted by name within each family.

Each card's icon is `imgs/fallacy-icons.svg#<slug>`, where the slug is the
fallacy name lowercased with runs of other characters turned into hyphens
(apostrophes dropped). A new fallacy needs a matching <symbol> in that file;
the script fails if one is missing.

Standard library only.
"""

from __future__ import annotations

import argparse
import csv
import html
import re
import sys
from pathlib import Path

PAGE = Path("fallacies.html")
DATA = Path("data/Rhetological_Fallacies.csv")
ICONS = Path("imgs/fallacy-icons.svg")
START = "<!-- fallacies:start"
END = "<!-- fallacies:end -->"

# Display order, short CSS key, and a one-line description for each family
FAMILIES = [
    ("Appeal to the Mind", "mind", "Leaning on authority, popularity, novelty or tradition instead of evidence."),
    ("Appeal to Emotions", "emotions", "Swaying people with fear, pity, flattery or spite rather than reasons."),
    ("Faulty Deduction", "deduction", "Drawing conclusions the evidence doesn’t support."),
    ("Manipulating Content", "content", "Bending, hiding or inventing the facts an argument rests on."),
    ("Garbled Cause & Effect", "cause", "Mistaking sequence, coincidence or correlation for cause."),
    ("On the Attack", "attack", "Going after the person, or a distorted version of their argument, instead of the argument."),
]


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower().replace("'", "").replace("’", "")).strip("-")


def typeset(text: str) -> str:
    """Curly apostrophes and quotes, then HTML-escape."""
    text = re.sub(r'"([^"]*)"', "“\\1”", text)
    text = text.replace("'", "’")
    return html.escape(text, quote=False)


def family_label(name: str) -> str:
    # Sentence case for headings and chips: "Appeal to the mind"
    return name[0] + name[1:].lower()


def build(rows: list[dict], icon_ids: set[str]) -> str:
    known = {f[0] for f in FAMILIES}
    unknown = sorted({r["category"] for r in rows} - known)
    if unknown:
        raise SystemExit(f"build_fallacies.py: unknown categories in {DATA}: {unknown}")
    missing = sorted(slug(r["fallacy"]) for r in rows if slug(r["fallacy"]) not in icon_ids)
    if missing:
        raise SystemExit(f"build_fallacies.py: no icon in {ICONS} for: {', '.join(missing)}")

    i1, i2, i3 = "      ", "        ", "          "
    out = [f"{START} (generated by scripts/build_fallacies.py from {DATA}; edit the CSV, not this block) -->"]

    # Filter chips
    out.append(f'{i1}<div class="fallacy-chips" role="group" aria-label="Show one family of fallacies">')
    out.append(f'{i2}<button type="button" class="fallacy-chip" data-family="all" aria-pressed="true">All '
               f'<span class="fallacy-chip__n">{len(rows)}</span></button>')
    for name, key, _ in FAMILIES:
        n = sum(r["category"] == name for r in rows)
        out.append(f'{i2}<button type="button" class="fallacy-chip fam-{key}" data-family="{slug(name)}" aria-pressed="false">'
                   f'<span class="fallacy-chip__dot" aria-hidden="true"></span>{html.escape(family_label(name))} '
                   f'<span class="fallacy-chip__n">{n}</span></button>')
    out.append(f"{i1}</div>")
    out.append(f'{i1}<p class="fallacy-empty" id="fallacy-empty" hidden>No fallacies match your search. '
               f'<button type="button" class="fallacy-empty__clear">Show all</button></p>')

    # One section per family
    for name, key, blurb in FAMILIES:
        fam = slug(name)
        items = sorted((r for r in rows if r["category"] == name), key=lambda r: r["fallacy"].lower())
        out.append("")
        out.append(f'{i1}<section class="fallacy-family fam-{key}" id="{fam}" data-family="{fam}" aria-labelledby="{fam}-title">')
        out.append(f'{i2}<div class="fallacy-family__head">')
        out.append(f'{i3}<h2 id="{fam}-title">{html.escape(family_label(name))}</h2>')
        out.append(f"{i3}<p>{typeset(blurb)}</p>")
        out.append(f"{i2}</div>")
        out.append(f'{i2}<ul class="fallacy-grid">')
        for r in items:
            s = slug(r["fallacy"])
            out.append(f'{i3}<li class="fallacy-card" id="{s}">')
            out.append(f'{i3}  <div class="fallacy-card__top">')
            out.append(f'{i3}    <span class="fallacy-icon"><svg viewBox="0 0 24 24" aria-hidden="true" focusable="false">'
                       f'<use href="{ICONS}#{s}"></use></svg></span>')
            out.append(f'{i3}    <span class="fallacy-kicker">{html.escape(family_label(name))}</span>')
            out.append(f"{i3}  </div>")
            out.append(f'{i3}  <h3><a href="#{s}">{typeset(r["fallacy"])}</a></h3>')
            out.append(f'{i3}  <p class="fallacy-def">{typeset(r["definition"])}</p>')
            out.append(f'{i3}  <p class="fallacy-example"><span class="fallacy-example__label">Example</span> '
                       f'<q>{typeset(r["example"])}</q></p>')
            out.append(f"{i3}</li>")
        out.append(f"{i2}</ul>")
        out.append(f"{i1}</section>")
    out.append(f"{i1}{END}")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if fallacies.html is out of date; write nothing")
    args = ap.parse_args(argv)

    for path in (PAGE, DATA, ICONS):
        if not path.is_file():
            print(f"build_fallacies.py: run this from the repo root ({path} not found)", file=sys.stderr)
            return 2

    with DATA.open(encoding="utf-8", newline="") as fh:
        rows = [r for r in csv.DictReader(fh) if r.get("fallacy", "").strip()]
    icon_ids = set(re.findall(r'<symbol id="([^"]+)"', ICONS.read_text(encoding="utf-8")))

    old = PAGE.read_text(encoding="utf-8")
    start = old.find(START)
    end = old.find(END)
    if start < 0 or end < start:
        print(f"build_fallacies.py: {PAGE} has no '{START} ... {END}' block", file=sys.stderr)
        return 2
    new = old[:start] + build(rows, icon_ids) + old[end + len(END):]

    if args.check:
        if new != old:
            print(f"fallacies.html is out of date; run: python3 scripts/build_fallacies.py ({len(rows)} fallacies)")
            return 1
        print(f"fallacies.html is up to date ({len(rows)} fallacies)")
        return 0

    if new != old:
        PAGE.write_text(new, encoding="utf-8")
        print(f"rebuilt fallacies.html ({len(rows)} fallacies)")
    else:
        print(f"fallacies.html already up to date ({len(rows)} fallacies)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
